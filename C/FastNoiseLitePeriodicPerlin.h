static inline float fnlp_quintic(float t) { return t*t*t*(t*(t*6.0f-15.0f)+10.0f); }
static inline float fnlp_gradient(uint32_t seed, uint32_t x, uint32_t y, uint32_t z,
                                  const float *delta, uint32_t dimensions) {
    uint32_t h = fnlp_hash(seed, x, y, z);
    h ^= h >> 15;
    if (dimensions == 2u) {
        uint32_t i = h & 254u;
        return delta[0]*FNLP_GRADIENTS_2D[i] + delta[1]*FNLP_GRADIENTS_2D[i+1u];
    }
    uint32_t i = h & 252u;
    return delta[0]*FNLP_GRADIENTS_3D[i] + delta[1]*FNLP_GRADIENTS_3D[i+1u]
         + delta[2]*FNLP_GRADIENTS_3D[i+2u];
}
static inline float fnlPeriodicPerlin(uint32_t seed, const float *p,
                                      const uint32_t *period, uint32_t dimensions) {
    uint32_t c0[3] = {0,0,0}, c1[3] = {0,0,0};
    float delta[3] = {0,0,0}, t[3] = {0,0,0}, v[8];
    for (uint32_t a = 0; a < dimensions; a++) {
        float cell = floorf(p[a]);
        c0[a] = fnlp_wrap((int32_t)cell, period[a]);
        c1[a] = (c0[a]+1u) % period[a];
        delta[a] = p[a]-cell;
        t[a] = fnlp_quintic(delta[a]);
    }
    for (uint32_t i = 0; i < (1u << dimensions); i++) {
        float d[3] = {delta[0] - (float)(i & 1u), delta[1] - (float)((i >> 1) & 1u),
                      delta[2] - (float)((i >> 2) & 1u)};
        v[i] = fnlp_gradient(seed, (i & 1u) ? c1[0] : c0[0],
                                  (i & 2u) ? c1[1] : c0[1],
                                  (i & 4u) ? c1[2] : c0[2], d, dimensions);
    }
    float xy0 = fnlp_lerp(fnlp_lerp(v[0],v[1],t[0]),fnlp_lerp(v[2],v[3],t[0]),t[1]);
    if (dimensions == 2u) return xy0 * 1.4247691104677813f;
    float xy1 = fnlp_lerp(fnlp_lerp(v[4],v[5],t[0]),fnlp_lerp(v[6],v[7],t[0]),t[1]);
    return fnlp_lerp(xy0,xy1,t[2]) * 0.964921414852142333984375f;
}
